#!/usr/bin/env bash
# Disposable, offline Zotero 10.0.6. Requires Linux, bubblewrap, Python 3,
# X11 and Hyprland's Lua control API. Opens silently on workspace 6.
set -euo pipefail
umask 077
REPO=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd -P)
ROOT="$REPO/.local-test/zotero"
APP="$ROOT/runtime/Zotero_linux-x86_64"
for tool in bwrap python hyprctl; do
  command -v "$tool" >/dev/null || { echo "Missing tool: $tool" >&2; exit 1; }
done
[[ -n ${DISPLAY:-} ]] || { echo 'An X11 DISPLAY is required.' >&2; exit 1; }
[[ -f "$APP/app/application.ini" ]] || { echo "Download/extract Zotero 10.0.6 first; see docs/testing/zotero-environment.md" >&2; exit 1; }
grep -qx 'Version=10.0.6' "$APP/app/application.ini" || { echo 'Expected Zotero 10.0.6' >&2; exit 1; }
# Session-only rule scoped to this launcher's unique WM_CLASS, not personal
# Zotero windows. Install before creating a window; never switch workspaces.
RULE='if zotero_compress_test_rule then
  zotero_compress_test_rule:set_enabled(true)
else
  zotero_compress_test_rule = hl.window_rule({
    name="zotero-compress-isolated-workspace",
    match={class="^ZoteroCompressionTest$"},
    workspace="6 silent", no_initial_focus=true
  })
end'
if ! reply=$(hyprctl eval "$RULE") || [[ "$reply" != ok ]]; then
  echo "Cannot install silent workspace-6 rule; refusing to launch: $reply" >&2
  exit 1
fi
mkdir -p "$ROOT"/{profile,data,logs,home,config,cache,xdg-data,tmp,xdg-runtime}
chmod 700 "$ROOT/xdg-runtime"
# Reapply safety preferences at every launch. Never read/copy host preferences.
python - "$ROOT" <<'PY'
import json
import pathlib
import sys
root = pathlib.Path(sys.argv[1])
prefs = {
    "extensions.zotero.useDataDir": True,
    "extensions.zotero.dataDir": str(root / "data"),
    "extensions.zotero.sync.autoSync": False,
    "extensions.zotero.sync.storage.enabled": False,
    "extensions.zotero.sync.storage.groups.enabled": False,
    "extensions.zotero.automaticScraperUpdates": False,
    "extensions.zotero.firstRun2": False,
    "extensions.zotero.firstRunGuidance": False,
    "app.update.auto": False,
    "app.update.enabled": False,
    "extensions.update.enabled": False,
    "datareporting.healthreport.uploadEnabled": False,
    "toolkit.telemetry.enabled": False,
}
(root / "profile" / "user.js").write_text(
    "// Disposable test profile: regenerated by launch-zotero.sh\n" +
    "".join(f"user_pref({json.dumps(key)}, {json.dumps(value)});\n" for key, value in prefs.items())
)
PY
# No home, /run, host /tmp, session bus, or network is exposed. The repository
# is read-only except .local-test, so linked attachment copies belong there.
# X11 is the only desktop service exposed; it is not a hostile-code sandbox.
exec bwrap \
  --unshare-user --unshare-pid --unshare-net --unshare-ipc --unshare-uts \
  --new-session --die-with-parent \
  --ro-bind /usr /usr --symlink usr/bin /bin \
  --symlink usr/lib /lib --symlink usr/lib /lib64 \
  --ro-bind /etc /etc --ro-bind /sys /sys \
  --proc /proc --dev /dev --tmpfs /tmp \
  --ro-bind /tmp/.X11-unix /tmp/.X11-unix \
  --ro-bind "$REPO" "$REPO" --bind "$REPO/.local-test" "$REPO/.local-test" \
  --clearenv \
  --setenv PATH /usr/bin:/bin --setenv LANG C.UTF-8 \
  --setenv HOME "$ROOT/home" \
  --setenv XDG_CONFIG_HOME "$ROOT/config" \
  --setenv XDG_CACHE_HOME "$ROOT/cache" \
  --setenv XDG_DATA_HOME "$ROOT/xdg-data" \
  --setenv XDG_RUNTIME_DIR "$ROOT/xdg-runtime" \
  --setenv TMPDIR "$ROOT/tmp" --setenv DISPLAY "$DISPLAY" \
  --setenv MOZ_ENABLE_WAYLAND 0 --setenv MOZ_LEGACY_PROFILES 1 \
  --chdir "$REPO" \
  "$APP/zotero-bin" -app "$APP/app/application.ini" \
  -no-remote -profile "$ROOT/profile" --class ZoteroCompressionTest "$@"
